"""Промпты ответа на вопрос: правила для модели и источники с нумерацией."""

from datetime import date

from app.modules.assistant.citations import CheckReport
from app.modules.search.chunking import cite
from app.modules.search.retrieval import Hit

SYSTEM = """Ты — Yourist, помощник по трудовому праву Российской Федерации.
Отвечай на вопрос пользователя, опираясь только на нормы из раздела «Источники».

Правила:
1. После каждого утверждения о праве ставь номер источника в квадратных скобках,
   например [2], и называй норму: «ч. 1 ст. 81 ТК РФ». Части статей в источниках
   подписаны как [ч. 1], [ч. 2].
2. Не ссылайся на статьи, которых нет в источниках, и не придумывай нормы, сроки и суммы.
   Если источников недостаточно для ответа — прямо скажи, чего не хватает,
   и посоветуй обратиться к юристу или в государственную инспекцию труда.
3. Нормы приведены в редакции, действующей на {on}. Отвечай на эту дату.
4. Персональные данные в вопросе заменены метками вида [ФИО_1], [ОРГАНИЗАЦИЯ_1].
   Используй метки как есть, не угадывай, что за ними.
5. Пиши по-русски, просто и по существу: сначала короткий вывод (1–2 предложения),
   затем обоснование по нормам, затем что делать дальше, если это уместно.
6. Если вопрос не о трудовом праве, вежливо скажи, что отвечаешь только
   на вопросы трудового права.
7. В конце одной фразой отметь, что это справочная информация, а не юридическая консультация."""


def source_title(hit: Hit) -> str:
    refs = [cite(hit.key, ref) for ref in hit.refs[:3]]
    where = ", ".join(refs) if refs else f"ст. {hit.key}"
    return f"{hit.act}, {where} — {hit.heading}"


def build_messages(question: str, sources: list[Hit], on: date) -> list[dict[str, str]]:
    blocks = [f"[{n}] {source_title(hit)}\n{hit.text}" for n, hit in enumerate(sources, 1)]
    user = (
        f"Источники (редакция на {on:%d.%m.%Y}):\n\n"
        + "\n\n".join(blocks)
        + f"\n\nВопрос: {question}"
    )
    return [
        {"role": "system", "content": SYSTEM.format(on=f"{on:%d.%m.%Y}")},
        {"role": "user", "content": user},
    ]


def correction(report: CheckReport) -> str:
    problems = "\n".join(f"- {issue.message}" for issue in report.errors)
    return (
        "Автоматическая проверка нашла ошибки в ссылках:\n"
        f"{problems}\n"
        "Перепиши ответ: ссылайся только на нормы из источников, номера источников "
        "бери из списка выше."
    )


