import pytest

from app.modules.deid import names, rules
from app.modules.deid.rules import inn_valid, luhn_valid, ogrn_valid, snils_valid
from app.modules.deid.service import _select


def found(text: str) -> list[tuple[str, str]]:
    entities = _select([*rules.find(text), *names.find(text)])
    return [(e.type, text[e.start : e.end]) for e in entities]


def test_checksums():
    # реквизиты ПАО Сбербанк из ЕГРЮЛ и учебные номера с верной контрольной суммой
    assert inn_valid("7707083893") and not inn_valid("7707083894")
    assert inn_valid("500100732259") and not inn_valid("500100732258")
    assert ogrn_valid("1027700132195") and not ogrn_valid("1027700132196")
    assert snils_valid("112-233-445 95") and not snils_valid("112-233-445 96")
    assert luhn_valid("4276 3801 2345 6787") and not luhn_valid("4276 3801 2345 6788")


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("пишите на maria.ivanova@mail.ru.", [("EMAIL", "maria.ivanova@mail.ru")]),
        ("звоните +7 (916) 123-45-67", [("ТЕЛЕФОН", "+7 (916) 123-45-67")]),
        ("или 89161234567", [("ТЕЛЕФОН", "89161234567")]),
        ("ИНН 7707083893", [("ИНН", "7707083893")]),
        ("СНИЛС 112-233-445 95", [("СНИЛС", "112-233-445 95")]),
        ("ОГРН 1027700132195", [("ОГРН", "1027700132195")]),
        ("паспорт серии 4506 № 123456", [("ПАСПОРТ", "4506 № 123456")]),
        ("документ 45 06 123456", [("ПАСПОРТ", "45 06 123456")]),
        ("карта 4276 3801 2345 6787", [("КАРТА", "4276 3801 2345 6787")]),
        ("р/с 40817810099910004312", [("СЧЁТ", "40817810099910004312")]),
        ("уволили из ООО «Ромашка»", [("ОРГАНИЗАЦИЯ", "ООО «Ромашка»")]),
        ("пишите в t.me/ivan_petrov.", [("ПРОФИЛЬ", "t.me/ivan_petrov")]),
        ("ник @ivan_petrov_88", [("ПРОФИЛЬ", "@ivan_petrov_88")]),
        ("живу: ул. Ленина, д. 5, кв. 12", [("АДРЕС", "ул. Ленина, д. 5, кв. 12")]),
        ("родилась 12.03.1985, уволена 01.02.2026", [("ДАТА_РОЖДЕНИЯ", "12.03.1985")]),
        ("1990 г.р.", [("ДАТА_РОЖДЕНИЯ", "1990 ")]),
    ],
)
def test_rules_find(text, expected):
    assert found(text) == expected


@pytest.mark.parametrize(
    "text",
    [
        # сроки, суммы, номера статей и приказов — не персональные данные
        "Испытательный срок 3 месяца, оклад 85000 рублей, приказ № 123 от 01.02.2026.",
        "Можно ли уволить по п. 6 ч. 1 ст. 81 ТК РФ за прогул 15.03.2026?",
        "Работодатель не платит зарплату с 2019 года, номер договора 1234567890.",
        "Вера в справедливость пропала. Надежда только на суд.",
        "Трудовой кодекс Российской Федерации, Федеральный закон № 152-ФЗ.",
    ],
)
def test_no_false_positives(text):
    assert found(text) == []


@pytest.mark.parametrize(
    ("text", "person"),
    [
        ("Меня, Иванову Марию Петровну, уволили", "Иванову Марию Петровну"),
        ("Зайцев Иван Петрович не согласовал", "Зайцев Иван Петрович"),
        ("Директор Сидоренко А.В. сказал", "Сидоренко А.В."),
        ("приказ подписал И. И. Кузнецов", "И. И. Кузнецов"),
        ("а начальник Петров орёт на меня", "Петров"),
        ("а Роза из бухгалтерии молчит", "Роза"),
        ("Мария работает со мной", "Мария"),
    ],
)
def test_person_names(text, person):
    assert ("ФИО", person) in found(text)


@pytest.mark.parametrize(
    ("text", "person"),
    [
        # так текст выдаёт распознавание речи — без заглавных букв и знаков
        ("здравствуйте меня зовут смирнова анна юрьевна я работаю", "смирнова анна юрьевна"),
        ("начальник иван петрович кузнецов уволил меня", "иван петрович кузнецов"),
    ],
)
def test_lowercase_names_with_patronymic(text, person):
    assert ("ФИО", person) in found(text)


def test_lowercase_without_patronymic_is_left_to_llm():
    # без отчества строчные слова не трогаем: «вера», «надежда», «роза» — обычные слова
    assert found("вера и надежда остались, а роза завяла") == []
